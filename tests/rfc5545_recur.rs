//! Worked recurrence examples of RFC 5545 3.8.5.3.
//!
//! Every case is transcribed from the examples the RFC prints under the
//! `RRULE` property: the rule, the `DTSTART` it runs from, and the occurrences
//! the RFC lists for it. Nothing here is computed, inferred or corrected. Where
//! the RFC elides a stretch with `...`, only the printed dates are kept and the
//! case is marked truncated, which asserts a prefix rather than the whole
//! expansion.
//!
//! The RFC states its occurrences as America/New_York wall-clock times and
//! labels each block EDT or EST. Expansion is civil, so those labels carry no
//! information here and every occurrence is the local time the RFC prints.
//! `UNTIL` is likewise read as the civil time it spells, not converted from
//! UTC into the zone of the start.

use ical::recur::{IcalRecurDateTime, IcalRecurRule, expand::IcalRecurExpand};

/// One worked example: a rule, the start it runs from, and the occurrences
/// RFC 5545 3.8.5.3 prints for it.
struct Case {
    /// The RFC's own description of the example.
    name: &'static str,
    /// The rule as the RFC writes it, unfolded onto one line.
    rule: &'static str,
    /// The `DTSTART` value of the example, as a civil local time.
    start: IcalRecurDateTime,
    /// Verbatim from the RFC.
    expect: &'static [IcalRecurDateTime],
    /// True when the RFC elides the tail with "...".
    truncated: bool,
}

/// Builds an occurrence at 9:00 AM, the local time every start in this section
/// recurs at.
const fn am9(year: i32, month: u8, day: u8) -> IcalRecurDateTime {
    at(year, month, day, 9, 0)
}

/// Builds an occurrence at an explicit local time. No example in this section
/// carries a non-zero second.
const fn at(year: i32, month: u8, day: u8, hour: u8, minute: u8) -> IcalRecurDateTime {
    IcalRecurDateTime {
        year,
        month,
        day,
        hour,
        minute,
        second: 0,
    }
}

