/// Expands every transcribed example and compares it to what the RFC prints.
///
/// A complete case takes one occurrence more than the RFC prints, so a rule
/// yielding too many fails on length. A truncated case takes exactly as many as
/// the RFC prints, which asserts a prefix.
#[test]
fn rfc5545_examples_expand() {
    for case in CASES {
        let rule = IcalRecurRule::parse(case.rule)
            .unwrap_or_else(|err| panic!("{}: {}: {err}", case.name, case.rule));
        let take = case.expect.len() + usize::from(!case.truncated);
        let got: Vec<IcalRecurDateTime> =
            IcalRecurExpand::new(rule, case.start).take(take).collect();

        assert_eq!(got, case.expect, "{}: {}", case.name, case.rule);
    }
}
